#!/usr/bin/env node
// Regenerates templates/index.mjs verbatim from the vendored .ts files.
// Run after re-copying templates/ from upstream (see headers in templates/*.ts).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const FILES = [
  ["professional", "user-prompt-professional.ts"],
  ["professional_en", "user-prompt-professional_en.ts"],
  ["basic", "user-prompt-basic.ts"],
  ["planning", "user-prompt-planning.ts"],
];

const here = fileURLToPath(new URL("../templates/", import.meta.url));

// Each .ts holds exactly two `content: \`...\`` template literals (system, user);
// the vendored files contain no inner backticks, but escape anyway so future
// upstream edits can't silently break generation.
const extract = (src) => {
  const spans = [...src.matchAll(/content:\s*`([^`]*)`/g)].map((m) => m[1]);
  if (spans.length !== 2) throw new Error(`expected 2 template literals, got ${spans.length}`);
  return spans;
};
const header = (src) => src.slice(0, src.indexOf("import")).trimEnd();

const lit = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

let out = `// GENERATED by tools/gen-templates.mjs — verbatim string data from the
// vendored .ts files in this directory. Do not edit by hand; re-run the tool
// after re-copying from upstream. Upstream: linshenkx/prompt-optimizer
// (develop 62b49a1f, 2026-11-18), AGPL-3.0-only — see headers below.

`;
for (const [id, file] of FILES) {
  const src = readFileSync(here + file, "utf8");
  const [system, user] = extract(src);
  out += `${header(src).replace(/^/gm, "// ")}\n\n`;
  out += `const ${id.replace(/[^a-z_]/g, "_")} = {\n  system: ${lit(system)},\n  user: ${lit(user)},\n};\n\n`;
}
out += `const templates = {
  professional,
  professional_en,
  basic,
  planning,
};

// Unknown id returns undefined (no throw) so callers can fail open.
export function getTemplate(id) {
  return templates[id];
}
`;
writeFileSync(here + "index.mjs", out);

// Self-check: the generated module must evaluate to the exact extracted bytes.
const { getTemplate } = await import(here + "index.mjs");
for (const [id, file] of FILES) {
  const [system, user] = extract(readFileSync(here + file, "utf8"));
  const t = getTemplate(id);
  if (!t || t.system !== system || t.user !== user) throw new Error(`mismatch: ${id}`);
  console.log(`${id}: ok (${system.length}+${user.length} chars)`);
}

#!/usr/bin/env node
// Regenerate the runtime templates after updating the local text or vendored headers.
import { readFileSync, writeFileSync } from "node:fs";
import { systems, user } from "../templates/overrides.mjs";

const files = {
  professional: "user-prompt-professional.ts",
  professional_en: "user-prompt-professional_en.ts",
  basic: "user-prompt-basic.ts",
  planning: "user-prompt-planning.ts",
};

const here = new URL("../templates/", import.meta.url);
let out = "// GENERATED by tools/gen-templates.mjs from templates/overrides.mjs.\n// Upstream provenance for each adapted template is recorded below.\n\n";
out += 'import { promptContentVersion } from "../lib/prompts.mjs";\n\n';
out += "const templates = {\n";
for (const [id, file] of Object.entries(files)) {
  const source = readFileSync(new URL(file, here), "utf8");
  const header = source.match(/^(?:\/\/[^\n]*\n)+/);
  if (!header) throw new Error(`missing provenance header: ${file}`);
  out += header[0].trimEnd().replace(/^/gm, "  ") + "\n";
  out += `  ${id}: {\n    system: ${JSON.stringify(systems[id])},\n    user: ${JSON.stringify(user)},\n  },\n`;
}
out += `};

export const contentVersion = promptContentVersion(templates);

export function getTemplate(id) {
  return templates[id];
}
`;
const output = new URL("index.mjs", here);
writeFileSync(output, out);

const { getTemplate } = await import(output);
for (const id of Object.keys(files)) {
  const t = getTemplate(id);
  if (!t.system || t.system !== systems[id] || t.user !== user) throw new Error(`mismatch: ${id}`);
  console.log(`${id}: ok (${t.system.length}+${t.user.length} chars)`);
}
